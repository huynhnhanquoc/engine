//go:build ignore

// casing_gen writes casing_table.go: the case mappings node gives (V8 with ICU, Unicode's full mappings) that differ
// from Go's one-to-one unicode.ToUpper and unicode.ToLower, each code point's whole result. Run from core/value with
// node installed, after a Go or a node whose Unicode moved: go generate (casing.go), or go run casing_gen.go.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

const dumpScript = `const up = {}, low = {};
for (let c = 0; c <= 0x10FFFF; c++) {
  if (c >= 0xD800 && c <= 0xDFFF) continue;
  const s = String.fromCodePoint(c);
  if (s.toUpperCase() !== s) up[c] = s.toUpperCase();
  if (s.toLowerCase() !== s) low[c] = s.toLowerCase();
}
process.stdout.write(JSON.stringify({ up, low, node: process.version, unicode: process.versions.unicode, icu: process.versions.icu }));`

type dump struct {
	Up, Low            map[string]string
	Node, Unicode, ICU string
}

// differences are the code points whose mapping in m (node's, a code point to its result) is not what simple gives,
// a code point node leaves as it is among them.
func differences(m map[string]string, simple func(rune) rune) ([]rune, map[rune]string) {
	out := map[rune]string{}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		mapped, ok := m[strconv.Itoa(int(r))]
		if !ok {
			mapped = string(r)
		}
		if string(simple(r)) != mapped {
			out[r] = mapped
		}
	}
	keys := make([]rune, 0, len(out))
	for r := range out {
		keys = append(keys, r)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	return keys, out
}

func literal(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r < 0x80 && r >= 0x20 && r != '"' && r != '\\':
			b.WriteRune(r)
		case r <= 0xFFFF:
			fmt.Fprintf(&b, "\\u%04X", r)
		default:
			fmt.Fprintf(&b, "\\U%08X", r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func main() {
	raw, err := exec.Command("node", "-e", dumpScript).Output()
	if err != nil {
		fmt.Fprintln(os.Stderr, "casing_gen: node:", err)
		os.Exit(1)
	}
	var d dump
	if err := json.Unmarshal(raw, &d); err != nil {
		fmt.Fprintln(os.Stderr, "casing_gen:", err)
		os.Exit(1)
	}
	upKeys, up := differences(d.Up, unicode.ToUpper)
	lowKeys, low := differences(d.Low, unicode.ToLower)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by casing_gen.go from node %s (ICU %s, Unicode %s) against Go's unicode %s; DO NOT EDIT.\n\n",
		d.Node, d.ICU, d.Unicode, unicode.Version)
	b.WriteString("package value\n\n")
	b.WriteString("// upperDifferences and lowerDifferences are the code points whose toUpperCase and toLowerCase, as node gives them\n")
	b.WriteString("// (Unicode's full mappings, SpecialCasing.txt's unconditional ones among them), are not what Go's one-to-one\n")
	fmt.Fprintf(&b, "// unicode.ToUpper and unicode.ToLower give: %d and %d of them (casing.go). Final sigma is casing.go's rule.\n", len(upKeys), len(lowKeys))
	b.WriteString("var upperDifferences = map[rune]string{\n")
	for _, r := range upKeys {
		fmt.Fprintf(&b, "\t0x%04X: %s,\n", r, literal(up[r]))
	}
	b.WriteString("}\n\nvar lowerDifferences = map[rune]string{\n")
	for _, r := range lowKeys {
		fmt.Fprintf(&b, "\t0x%04X: %s,\n", r, literal(low[r]))
	}
	b.WriteString("}\n")
	if err := os.WriteFile("casing_table.go", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "casing_gen:", err)
		os.Exit(1)
	}
	fmt.Println("casing_table.go:", len(upKeys), "upper,", len(lowKeys), "lower")
}
